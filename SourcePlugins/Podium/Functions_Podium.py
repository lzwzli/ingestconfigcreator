# Customize column list
def customize_col_list(table_name:str, col_list:list):
    if table_name.upper() == "PODIUMCONTACTS":
        col_list_custom = []
        for col in col_list:
            if col[1].upper() == "MIDDLE_NAME" or col[1].upper() == "LAST_NAME":
                continue
            elif col[1].upper() == "FIRST_NAME":
                col_list_custom.append(["name", "name", "VARCHAR(16777216)"])
            else:
                col_list_custom.append(col)
    else:
        col_list_custom = col_list

    return col_list_custom

