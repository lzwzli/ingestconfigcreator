# Sources Append
# ----------------------------------------------------------------
def fn_sources_append(worksheet:object, db_folder:str, sources_obj:object, runlog:object, repo_root_folder:str, client:str, source_name:str):
    runlog.log("Running Formstack specific sources append function")

    # get table name
    table_name = worksheet.table_name().lower()

    sources_obj.append("rowCountCheckOverride", 1)

    if table_name.upper() == "FORMSTACKSUBMISSIONS":
        sources_obj.append("dlpColumns", "MISCDATA")
    elif table_name.upper() == "FORMSTACKFORMDETAILSBLOB" or table_name.upper() == "FORMSTACKSUBMISSIONSBLOB":
        # get column that is Variant data type
        variant_col = clookup(worksheet=worksheet.worksheet, lookup_col="DataType", lookup_val="VARIANT", return_col="ColumnName")

        sources_obj.append("dlpColumns", variant_col[0])

    return

