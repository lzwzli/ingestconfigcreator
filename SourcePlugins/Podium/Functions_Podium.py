            #     uniquesp.newline(f"\t\t\t\t\tTHEN SPLIT_PART(IFNULL(TRIM(CAST(NAME AS STRING)), ''), ' ', 2)")
            #     uniquesp.newline(f"\t\t\t\t\tELSE ''")
            #     uniquesp.newline(f"\t\t\t\tEND MIDDLE_NAME,")
            # # special handling for last name
            # elif colname.upper() == 'LAST_NAME':
            #     uniquesp.newline(f"\t\t\t\tCASE")
            #     uniquesp.newline(f"\t\t\t\t\tWHEN NAME ILIKE '% % %'")
            #     uniquesp.newline(f"\t\t\t\t\tTHEN SPLIT_PART(IFNULL(TRIM(CAST(NAME AS STRING)), ''), ' ', 3)")
