# Append Business Rules
# ----------------------------------------------------------------
def fn_busrules_append(worksheet:object, bus_rule_obj:object, db_folder:str, runlog:object):
    runlog.log("Running Formstack specific busrules append function")

    table_name = worksheet.table_name()

    # ----------------------------------------------------------------
    # FormstackSubmissions
    # ----------------------------------------------------------------
    if table_name.upper() == "FORMSTACKSUBMISSIONS":
        runlog.log("Generate FormstackSubmissions Business Rules.")

        # get client name
        client = db_folder.split(os.sep)
        client.reverse()
        client = client[2].upper()

        # import client specific submissions_2_0 rule
        try:
            # load client specific submissions_bus_rule file
            submissions_busrule_plugin_name = f"SourcePlugins.Formstack.Functions_Formstack_Submissions_Busrule_2_0_{client}"
            submissions_busrule_plugin = import_module(submissions_busrule_plugin_name)
            fn_submissions_bus_rule_2_0 = getattr(submissions_busrule_plugin, "fn_submissions_bus_rule_2_0")
            runlog.log(f"{indent}Using {submissions_busrule_plugin_name} to generate Submissions bus rule 2_0.")
        except:
            runlog.log(
                f"{indent}{submissions_busrule_plugin_name} not found. Using standard bus rule to generate Submissions bus rule 2_0.")
            runlog.log("")
            # load basic flatten
            try:
                submissions_busrule_plugin = import_module("SourcePlugins.Formstack.Functions_Formstack_Submissions_Busrule_2_0_STD")
                fn_submissions_bus_rule_2_0 = getattr(submissions_busrule_plugin, "fn_submissions_bus_rule_2_0")
            except:
                runlog.log(
                    f"{indent}ERROR: Functions_Formstack_Submissions_Busrule_2_0_Std not found. Terminating processing.")
                raise Exception

        # import client specific submissions_3_0 rule
        try:
            # load client specific submissions_bus_rule file
            submissions_busrule_plugin_name = f"SourcePlugins.Formstack.Functions_Formstack_Submissions_Busrule_3_0_{client}"
            submissions_busrule_plugin = import_module(submissions_busrule_plugin_name)
            fn_submissions_bus_rule_3_0 = getattr(submissions_busrule_plugin, "fn_submissions_bus_rule_3_0")
            runlog.log(f"{indent}Using {submissions_busrule_plugin_name} to generate Submissions bus rule 3_0.")
        except:
            runlog.log(
                f"{indent}{submissions_busrule_plugin_name} not found. Using standard bus rule to generate Submissions bus rule 3_0.")
            runlog.log("")
            # load basic flatten
            try:
                submissions_busrule_plugin = import_module("SourcePlugins.Formstack.Functions_Formstack_Submissions_Busrule_3_0_STD")
                fn_submissions_bus_rule_3_0 = getattr(submissions_busrule_plugin, "fn_submissions_bus_rule_3_0")
            except:
                runlog.log(
                    f"{indent}ERROR: Functions_Formstack_Submissions_Busrule_3_0_Std not found. Terminating processing.")
                raise Exception

        # define variables
        output_folder = f"{db_folder}ForReferenceOnly{os.sep}FormstackSubmissions_BusRules{os.sep}"
        col_list = worksheet.columns()
        pk_list = worksheet.primary_keys()

        # get master form id
        master_form_id = str(worksheet.tableinfo()["MasterFormID"]).strip()

        # # get column that is Variant data type
        # variant_col = str(worksheet.tableinfo()["VariantColumnName"]).strip()

        # get FieldID column
        FieldID_col = str(worksheet.tableinfo()["FieldIDColumnName"]).strip()

        # get FieldName column
        FieldName_col = str(worksheet.tableinfo()["FieldNameColumnName"]).strip()

        # get FieldLabel column
        FieldLabel_col = str(worksheet.tableinfo()["FieldLabelColumnName"]).strip()

        # get FieldID column
        FormID_col = str(worksheet.tableinfo()["FormIDColumnName"]).strip()

        # get FormName column
        FormName_col = str(worksheet.tableinfo()["FormNameColumnName"]).strip()

        # ----------------------------------------------------------------
        # Rule 1_0
        # ----------------------------------------------------------------
        busrule = {}
        busrule["ruleName"] = "FormstackSubmissions_1_0"
        busrule["runOrder"] = 1
        busrule["runPosition"] = 0

        ruleQuerydoc = Document()
        ruleQuerydoc.append("TRUNCATE TABLE &database.IMPORT.FORMSTACKSUBMISSIONS;")

        # write out Rule Query to file
        filewrite(folder=output_folder, filename="FormstackSubmissions_1_0 TRUNCATE IMPORT FORMSTACKSUBMISSIONS RULE QUERY.sql", content=ruleQuerydoc.out())

        busrule["ruleQuery"] = ruleQuerydoc.out_str()

        bus_rule_obj.add_rule(busrule)

        # ----------------------------------------------------------------
        # Rule 2_0
        # ----------------------------------------------------------------
        busrule = {}
        busrule["ruleName"] = "FormstackSubmissions_2_0"
        busrule["runOrder"] = 2
        busrule["runPosition"] = 0

        # splitting out this into its own function in case client specific versions need to be created
        ruleQuerydoc = fn_submissions_bus_rule_2_0(col_list = col_list, pk_list = pk_list, field_id_col = FieldID_col, field_name_col = FieldName_col, field_label_col = FieldLabel_col, form_name_col = FormName_col, form_id_col = FormID_col, master_form_id = master_form_id)

        # write out Rule Query to file
        filewrite(folder=output_folder, filename="FormstackSubmissions_2_0 INSERT IMPORT FORMSTACKSUBMISSIONS RULE QUERY.sql", content=ruleQuerydoc.out())

        busrule["ruleQuery"] = ruleQuerydoc.out_str()

        bus_rule_obj.add_rule(busrule)

        # ----------------------------------------------------------------
        # Rule 3_0
        # ----------------------------------------------------------------
        busrule = {}
        busrule["ruleName"] = "FormstackSubmissions_3_0"
        busrule["runOrder"] = 3
        busrule["runPosition"] = 0

        # splitting out this into its own function in case client specific versions need to be created
        ruleQuerydoc = fn_submissions_bus_rule_3_0(col_list = col_list, field_id_col = FieldID_col, field_name_col = FieldName_col, field_label_col = FieldLabel_col, form_name_col = FormName_col, form_id_col = FormID_col, master_form_id = master_form_id)

        # write out Rule Query to file
        filewrite(folder=output_folder, filename="FormstackSubmissions_3_0 INSERT IMPORT FORMSTACKSUBMISSIONS RULE QUERY.sql", content=ruleQuerydoc.out())

        busrule["ruleQuery"] = ruleQuerydoc.out_str()

        bus_rule_obj.add_rule(busrule)

    return

